        else -> listOf(word)
    }
    fun matches(query: List<String>, document: List<String>): Boolean = distance(query,document)==0
    /** All meaningful words survive. At most ONE typo across the entire phrase. */
    fun distance(query: List<String>, document: List<String>): Int {
        var errors=0
        for(q in query) {
            if(alternatives(q).any { part -> document.any { it.startsWith(part) } }) continue
            if(q.length>=5 && document.any { it.length>=5 && oneEdit(q,it) }) errors++ else return 99
            if(errors>1) return 99
        }
        return errors
    }
    private fun oneEdit(a: String,b: String): Boolean {
        if(kotlin.math.abs(a.length-b.length)>1) return false
        if(a.length==b.length) {
            val changed=a.indices.filter {a[it]!=b[it]}
            return changed.size==1 || (changed.size==2 && changed[1]==changed[0]+1 && a[changed[0]]==b[changed[1]] && a[changed[1]]==b[changed[0]])
        }
        val short=if(a.length<b.length) a else b;val long=if(a.length<b.length) b else a
        var i=0;var j=0;var skipped=false
        while(i<short.length && j<long.length) {
            if(short[i]==long[j]) {i++;j++} else {if(skipped)return false;skipped=true;j++}
        }
        return true
    }
